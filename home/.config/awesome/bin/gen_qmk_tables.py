#!/usr/bin/env python3
"""Generate the static QMK decoding tables the keymap popup needs.

The keymap itself is read live from the keyboard (qmk_keymap_dump.py). What the
keyboard sends are raw 16-bit keycodes and matrix positions, so decoding needs
two things that never change at runtime: QMK's keycode numbering and the
board's physical key layout. This writes both as Lua modules:

  qmk_keycodes.lua      keycode number -> name/label, plus the QK_* ranges
  ergodox_geometry.lua  matrix (row, col) -> x, y, w, h in key units

Run inside the qmk_cli:phil image (the host Python is too new for the qmk
module), from the qmk_firmware checkout:

  docker run --rm --user $(id -u):$(id -g) -e HOME=/tmp -w /qmk_firmware \
      -e PYTHONPATH=/qmk_firmware/lib/python \
      -v "$PWD":/qmk_firmware -v "$(readlink -f ~/.config/awesome)":/awesome \
      qmk_cli:phil python3 /awesome/bin/gen_qmk_tables.py --out /awesome
"""

import argparse
import json
import os
import subprocess

from qmk.keycodes import load_spec

KEYBOARD = "ergodox_ez"
LAYOUT = "LAYOUT_ergodox"


def qmk_version():
    try:
        return subprocess.check_output(["git", "describe", "--tags"], text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def header(what, version):
    return (
        "-- Generated by bin/gen_qmk_tables.py from qmk_firmware %s; do not edit.\n"
        "-- %s\n" % (version, what)
    )


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_keycodes(out, version):
    spec = load_spec("latest")
    lines = [header("QMK keycode numbering: keycodes[number] = {key=, label=}; ranges[define] = {base, mask}.", version)]
    lines.append("return {")
    lines.append("  keycodes = {")
    for code, entry in spec["keycodes"].items():
        lines.append("    [%s] = {key = %s, label = %s}," % (
            code, lua_string(entry["key"]), lua_string(entry.get("label", entry["key"]))))
    lines.append("  },")
    lines.append("  ranges = {")
    for span, entry in spec["ranges"].items():
        base, mask = span.split("/")
        lines.append("    %s = {%s, %s}," % (entry["define"], base, mask))
    lines.append("  },")
    lines.append("}")
    with open(os.path.join(out, "qmk_keycodes.lua"), "w") as f:
        f.write("\n".join(lines) + "\n")
    return len(spec["keycodes"])


def write_geometry(out, version):
    with open(os.path.join("keyboards", KEYBOARD, "info.json")) as f:
        keys = json.load(f)["layouts"][LAYOUT]["layout"]
    width = max(k["x"] + k.get("w", 1) for k in keys)
    height = max(k["y"] + k.get("h", 1) for k in keys)
    lines = [header("%s %s: one entry per physical key, positions in key units." % (KEYBOARD, LAYOUT), version)]
    lines.append("return {")
    lines.append("  width = %g," % width)
    lines.append("  height = %g," % height)
    lines.append("  keys = {")
    for k in keys:
        row, col = k["matrix"]
        lines.append("    {row = %d, col = %d, x = %g, y = %g, w = %g, h = %g}," % (
            row, col, k["x"], k["y"], k.get("w", 1), k.get("h", 1)))
    lines.append("  },")
    lines.append("}")
    with open(os.path.join(out, "ergodox_geometry.lua"), "w") as f:
        f.write("\n".join(lines) + "\n")
    return len(keys)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--out", required=True, help="directory to write the Lua modules into")
    args = parser.parse_args()
    version = qmk_version()
    print("wrote %d keycodes" % write_keycodes(args.out, version))
    print("wrote %d keys" % write_geometry(args.out, version))


if __name__ == "__main__":
    main()
